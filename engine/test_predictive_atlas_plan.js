'use strict';
const assert=require('node:assert/strict');
const {compileTemplateAtlas}=require('./predictive_atlas_plan');
const rect=(x,w=80)=>({x,y:0,width:w,height:40});
const frames=Array.from({length:120},(_,i)=>({regions:[rect(0),rect(600)],complexity:1+(i%12)/12}));
const cfg={maxWidth:600,maxHeight:400,maxBytes:12*1024*1024,maxSlots:32,targetCost:13};
const staticTemplate=compileTemplateAtlas({sourceHash:'invariant',frameDescriptors:frames,config:cfg});
assert.equal(staticTemplate.staticPlan.frameCount,120);
const a=staticTemplate.planFor({label:'A'}),b=staticTemplate.planFor({label:'A much longer label',opacity:0.1});
assert.equal(a.cacheKey,b.cacheKey);
assert.deepEqual(a.batches,b.batches);
assert(a.batches.length>1);
assert(a.batches.every(x=>x.count<=32&&x.bytes<=cfg.maxBytes));
assert.equal(a.batches.reduce((s,b)=>s+b.count,0),120);
let called=0;
const dynamicFrames=Array.from({length:18},(_,i)=>props=>{called++;return {regions:[rect(0,props.scale*80),rect(600,props.scale*80)],complexity:1+(i%3)};});
const dynamicTemplate=compileTemplateAtlas({sourceHash:'dynamic',frameDescriptors:dynamicFrames,parameterDependencies:['scale'],config:cfg});
assert.equal(called,0,'no dynamic planning during template compilation');
const cache=new Map();
const p=dynamicTemplate.planFor({scale:1,label:'ignored'},cache);assert.equal(called,18);
const p2=dynamicTemplate.planFor({scale:1,label:'different'},cache);assert.equal(called,18);assert.deepEqual(p.batches,p2.batches);
const q=dynamicTemplate.planFor({scale:2},cache);assert.equal(called,36);assert.notDeepEqual(p.batches.map(x=>x.pixels),q.batches.map(x=>x.pixels));
assert.equal(dynamicTemplate.staticPlan,null);
assert.equal(q.batches.reduce((s,b)=>s+b.count,0),18);
assert.throws(()=>compileTemplateAtlas({sourceHash:'bad',frameDescriptors:[{regions:[rect(0,999999)]}],config:cfg}),/exceeds atlas/);
console.log(JSON.stringify({status:'PASS',staticBatches:a.batches.length,staticLargestBatch:Math.max(...a.batches.map(x=>x.count)),dynamicBatches:q.batches.length,cacheHitsVerified:true,renderOrCaptureCalls:0},null,2));
